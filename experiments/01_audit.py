"""Regenerate docs/DATA_AUDIT.md from the corpus. Every number in the paper's
data section comes from here, not from hand-counting."""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dripps import features, io, schema, stats  # noqa: E402

ORDER = [*schema.PT_VARIETIES, schema.REFERENCE_VARIETY]


def md_table(df: pd.DataFrame, index_name: str = "") -> str:
    head = f"| {index_name} | " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "---|" * (len(df.columns) + 1)
    def fmt(v):
        if isinstance(v, float):
            return f"{v:.3f}".rstrip("0").rstrip(".") if abs(v) < 1 else f"{v:g}"
        return str(v)

    rows = [
        f"| **{i}** | " + " | ".join(fmt(v) for v in r) + " |"
        for i, r in zip(df.index, df.to_numpy())
    ]
    return "\n".join([head, sep, *rows])


def main() -> None:
    df = io.load()
    df["variety"] = pd.Categorical(df["variety"], categories=ORDER, ordered=True)
    out = ["# DRIPPS data audit", "",
           "*Generated by `experiments/01_audit.py` -- do not edit by hand.*", ""]

    out += ["## Corpus size", "",
            md_table(df.groupby("variety", observed=True).size().to_frame("sentences"),
                     "variety"), ""]

    out += ["## Target: temporal relation (row %)", ""]
    tr = pd.crosstab(df["variety"], df[schema.TARGET])[list(schema.TR_LABELS)]
    pct = (tr.div(tr.sum(1), axis=0) * 100).round(1)  # noqa: E501
    combined = tr.astype(str) + " (" + pct.astype(str) + "%)"
    out += [md_table(combined, "variety"), "",
            "EP/AP/MP are posteriority-dominant; **BP inverts to anteriority-dominant**; "
            "British English is near-categorically anterior, so its cue weights are "
            "unidentifiable and it is used as a contrastive reference only.", ""]

    out += ["## Cue availability", ""]
    avail = pd.DataFrame({
        "non-final position %": df.groupby("variety", observed=True)["Position"]
            .apply(lambda s: (s != "Final").mean() * 100).round(1),
        "connector present %": df.groupby("variety", observed=True)["CNT"]
            .apply(lambda s: (s.str.strip() != "").mean() * 100).round(1),
        "stative main clause %": df.groupby("variety", observed=True)["ATMC"]
            .apply(lambda s: (s == "St").mean() * 100).round(1),
        "distinct tense labels": df.groupby("variety", observed=True)["TMC"]
            .nunique().astype(int),
    })
    out += [md_table(avail, "variety"), "",
            "BP patterns toward English on every dimension here.", ""]

    out += ["## Marginal association with TR (bias-corrected Cramer's V)", "",
            "Descriptive only: the cues are collinear, so these rank cues but "
            "overstate the independent contribution of the weaker ones "
            "(see `results/tables/cue_importance.csv`).", ""]
    rows = {}
    for variety, sub in df.groupby("variety", observed=True):
        rows[variety] = {c: stats.association(sub, c)["v"]
                         for c in schema.CUE_COLUMNS}
    marg_by_variety = pd.DataFrame(rows).T.round(3)
    marg_by_variety = marg_by_variety[list(schema.CUE_COLUMNS)]
    out += [md_table(marg_by_variety, "variety"), ""]

    out += ["## Definitional leakage", "",
            "`SR-SC` and `DR` are partly *defined* by temporal order and are excluded "
            "from every model by `dripps.leakage.assert_no_leakage`.", ""]
    leak = pd.DataFrame([stats.association(df, c) for c in schema.LEAKY_COLUMNS])
    out += [md_table(leak.set_index("cue")[["v", "chi2", "dof"]].round(3), "column"), ""]
    sr = df[df["SR-SC"].isin(["before", "after"])]
    b = sr[sr["SR-SC"] == "before"][schema.TARGET].value_counts().to_dict()
    a = sr[sr["SR-SC"] == "after"][schema.TARGET].value_counts().to_dict()
    out += [f"- `SR-SC == \"before\"` -> {b}", f"- `SR-SC == \"after\"` -> {a}",
            "- `DR == \"asynchrony\"` never co-occurs with `Simul`.", ""]

    out += ["## Data quality", ""]
    g = df.groupby("sentence_group").size()
    raw_lines = (ROOT / "data/raw/dripps_full.csv").read_text(encoding="utf-8").split("\n")
    semis = sum(1 for ln in raw_lines[1:] if ln.strip() and ln.count(";") > 10)
    nbsp_rows = int(df["Sentence"].str.contains("\u00a0").sum())
    nbsp_total = int(df["Sentence"].str.count("\u00a0").sum())
    aux = io.has_apc_auxiliary(df)
    n_aux = io.count_apc_auxiliary(df)
    pt, en = df.is_portuguese, ~df.is_portuguese
    out += [
        f"- **{(g > 1).sum()} sentences are duplicated** across {g[g > 1].sum()} rows "
        "(multi-APC sentences, one row per clause). All CV splits group on "
        "`sentence_group`; an ungrouped split leaks.",
        f"- **{semis} sentences contain a literal `;`** and the exporter does not "
        "quote fields, so a naive CSV read drops or truncates them. `dripps.io` "
        "splits positionally and rejoins.",
        f"- **{nbsp_rows} sentences contain non-breaking spaces** ({nbsp_total} "
        "occurrences) and one contains U+2028. `sentence_norm` normalises these "
        "for tokenisation and span regexes.",
        f"- **The APC span is not annotated.** Recovered from the auxiliary "
        f"(`dripps.schema.APC_AUXILIARY`): {int(aux[pt].sum())}/{int(pt.sum())} "
        f"Portuguese, {int(aux[en].sum())}/{int(en.sum())} English; "
        f"{int((n_aux > 1).sum())} sentences contain more than one auxiliary, so "
        "the span is ambiguous.",
        "",
    ]

    out += ["## Feature sparsity (Portuguese analysis set)", "",
            "Features below ~5% are retained but cannot support per-variety estimates; "
            "they rely on partial pooling.", ""]
    X = features.build(io.analysis_frame(df))
    sparse = (X.mean() * 100).round(1).sort_values().to_frame("% present")
    out += [md_table(sparse, "feature"), ""]

    path = ROOT / "docs/DATA_AUDIT.md"
    text = "\n".join(out)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
